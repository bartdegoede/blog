# scripts/ask_eval/length_report.py
"""Answer-length experiment: faithfulness by model x N sentences.

Reads results/length/*.jsonl (run_local.mjs --sentences N) and
results/judgements-length.jsonl (judge.py --runs-dir results/length), prints
the table and writes results/length/report.md.
"""

from __future__ import annotations

import json
from pathlib import Path

import click

try:  # pytest (pythonpath = ["scripts"])
    from ask_eval import report_lib as lib
except ImportError:  # run as a plain script
    import report_lib as lib  # type: ignore[no-redef]

HERE = Path(__file__).parent
RESULTS = HERE / "results"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def pct(n: int, d: int) -> str:
    return f"{n}/{d} ({100 * n / d:.0f}%)" if d else "n/a"


def render(rows: list[dict]) -> str:
    header = [
        "model",
        "N",
        "faithful (answerable)",
        "unsupported (answerable)",
        "invented (negatives)",
        "mean sentences",
        "mean tokens",
        "median wall/answer",
    ]
    lines = [
        "# Answer length vs faithfulness",
        "",
        (
            "Generated by `length_report.py`. Each N: system prompt 'at most N "
            "sentences', max_new_tokens = 60*N, early stop at N sentences, answer = "
            "formatAnswer(raw, N). Judge: judge.py with the length note. "
            "Invented = negative questions (ungated) labelled unsupported."
        ),
        "",
        "| " + " | ".join(header) + " |",
        "|" + "---|" * len(header),
    ]
    for r in rows:
        cells = [
            r["model"],
            str(r["n"]),
            pct(r["faithful"], r["answerable"]),
            pct(r["unsupported"], r["answerable"]),
            pct(r["invented"], r["negatives"]),
            f"{r['mean_sentences']:.2f}",
            f"{r['mean_tokens']:.1f}",
            f"{r['median_wall_ms'] / 1000:.1f} s",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


@click.command()
@click.option(
    "--judgements",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    default=RESULTS / "judgements-length.jsonl",
    show_default=True,
)
@click.option(
    "--runs-dir",
    type=click.Path(exists=True, file_okay=False, path_type=Path),
    default=RESULTS / "length",
    show_default=True,
)
def main(judgements: Path, runs_dir: Path) -> None:
    runs = [r for p in sorted(runs_dir.glob("*.jsonl")) for r in read_jsonl(p)]
    md = render(lib.length_table(read_jsonl(judgements), runs))
    click.echo(md)
    (runs_dir / "report.md").write_text(md)


if __name__ == "__main__":
    main()
